// Langue d'une réponse de Dalil -> langue des titres de ses sections
export function langueReponse(langue: string, texte: string, defaut: Langue): Langue {
  if (langue === 'ar') return 'ar';
  // Darija en écriture arabe : titres en arabe
  if (langue === 'darija') return /^[^A-Za-z]*[؀-ۿ]/.test(texte) ? 'ar' : 'darija';
  if (langue === 'fr' || langue === 'en') return langue;
  return defaut;
}
